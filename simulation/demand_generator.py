"""
BharatRoad Twin - Traffic Demand & Route Generator
==================================================
Generates realistic Indian traffic demand profiles (routes.rou.xml) with custom vehicle modal splits:
- 45% Two-Wheelers
- 25% Auto-Rickshaws
- 20% Passenger Cars
- 5%  City Buses
- 5%  LCVs / Heavy Goods Vehicles
"""

import os
import random
import xml.etree.ElementTree as ET
from xml.dom import minidom
from pathlib import Path


DEFAULT_MODAL_SPLIT = {
    "two_wheeler": 0.45,
    "auto_rickshaw": 0.25,
    "car": 0.20,
    "bus": 0.05,
    "lcv": 0.05
}


def generate_routes(edge_ids: list[str], total_vehicles: int = 500, duration_seconds: int = 3600, output_path: str = "routes.rou.xml") -> str:
    """
    Generates a SUMO routes file containing vehicle flows and individual vehicle departures
    distributed across the simulation duration based on Indian modal split.
    """
    routes_elem = ET.Element("routes")
    
    # Add comment
    comment = ET.Comment(" Generated by BharatRoad Twin Demand Generator ")
    routes_elem.append(comment)

    if not edge_ids or len(edge_ids) < 2:
        edge_ids = ["edge_001", "edge_002", "edge_003", "edge_004", "edge_005"]

    # Define main corridor route
    route_elem = ET.SubElement(routes_elem, "route", id="main_route", edges=" ".join(edge_ids))

    # Calculate count per vehicle type
    vtypes = list(DEFAULT_MODAL_SPLIT.keys())
    weights = list(DEFAULT_MODAL_SPLIT.values())

    depart_times = sorted([round(random.uniform(0, duration_seconds), 1) for _ in range(total_vehicles)])

    for i, depart in enumerate(depart_times):
        vtype = random.choices(vtypes, weights=weights, k=1)[0]
        v_id = f"veh_{vtype}_{i:04d}"
        ET.SubElement(routes_elem, "vehicle", {
            "id": v_id,
            "type": vtype,
            "route": "main_route",
            "depart": str(depart),
            "departPos": "free",
            "departSpeed": "max"
        })

    # Format pretty XML
    xml_str = minidom.parseString(ET.tostring(routes_elem, encoding="utf-8")).toprettyxml(indent="  ")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(xml_str)

    return output_path


if __name__ == "__main__":
    sample_edges = ["edge_001", "edge_002", "edge_003", "edge_004", "edge_005", "edge_006"]
    out_file = generate_routes(sample_edges, total_vehicles=300, duration_seconds=1800, output_path="sample_routes.rou.xml")
    print(f"Generated demand file at: {out_file}")
